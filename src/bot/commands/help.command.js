export async function helpCommand(ctx) {
  await ctx.reply(
    [
      'دستورات قابل استفاده:',
      '',
      '/search <نام محصول یا سؤال> — جستجوی محصول',
      '/ask <سؤال> — پرسش آزاد از دستیار هوشمند',
      '/help — نمایش این راهنما',
      '',
      'یا از دکمه «📋 مشاهده قیمت‌ها» پایین صفحه استفاده کنید.',
    ].join('\n')
  );
}
